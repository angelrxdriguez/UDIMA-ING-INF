from alg import *

ok = 0


def eq(name, got, want):
    global ok
    G = got if not isinstance(got, list) else [[Fr(x) for x in r] if isinstance(r, list) else Fr(r) for r in got]
    W = want if not isinstance(want, list) else [[Fr(x) for x in r] if isinstance(r, list) else Fr(r) for r in want]
    if not isinstance(got, list):
        G, W = Fr(got) if not isinstance(got, str) else got, Fr(want) if not isinstance(want, str) else want
    assert G == W, f'{name}: sale {got}, la guía dice {want}'
    ok += 1


def sistema(name, Aug, tipo, part=None, dirs=None):
    c = classify(Aug)[0]
    eq(name + ' tipo', c, tipo)
    if part is not None:
        p, d, _ = solve_param(Aug)
        assert check_solution(Aug, part), name + ' particular'
        for v in dirs or []:
            assert check_solution([r[:-1] + [0] for r in Aug], v), name + ' dirección'
        assert len(d) == len(dirs or []), name + ' nº de parámetros'
    global ok
    ok += 1


def dist2_punto_recta(Q, P, d):
    v = sub(Q, P)
    w = sub(v, proj(v, d))
    assert dot(w, d) == 0
    return norm2(w)


def dist2_punto_plano(Q, n, A):
    assert dot(n, A) == dot(n, A)
    v = sub(Q, A)
    return norm2(proj(v, n))


